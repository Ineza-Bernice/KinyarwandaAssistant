class TTSWrapper:
    """
    A wrapper class for different text-to-speech solutions
    """
    def __init__(self):
        self.detect_language = True
        print("TTS Wrapper initialized")

    def synthesize(self, text, lang=None, output_path=None):
        """
        Synthesize speech from text using the appropriate method based on language
        """
        if not lang and self.detect_language:
            # Detect language if not provided
            detected_lang, _ = langid.classify(text)
            lang = detected_lang
            print(f"Detected language: {lang}")

        # Default to English if no language is specified
        if not lang:
            lang = 'en'

        # Use gTTS for most languages
        print(f"Synthesizing text using gTTS: '{text}'")

        # Special handling for Kinyarwanda which might not be directly supported by gTTS
        if lang.lower() in ['rw', 'kinyarwanda']:
            print("Kinyarwanda detected, using closest available language approximation")
            # Use a related language like Swahili as fallback
            tts = gTTS(text=text, lang='sw', slow=False)
        else:
            # For other languages, use default gTTS behavior
            try:
                tts = gTTS(text=text, lang=lang, slow=False)
            except:
                print(f"Language {lang} not supported by gTTS, falling back to English")
                tts = gTTS(text=text, lang='en', slow=False)

        # Save audio file
        if not output_path:
            output_path = "/content/tts_output.mp3"
        tts.save(output_path)
        print(f"Audio saved to {output_path}")

        # Convert to wav if needed
        if output_path.endswith(".mp3"):
            from pydub import AudioSegment
            wav_path = output_path.replace(".mp3", ".wav")
            sound = AudioSegment.from_mp3(output_path)
            sound.export(wav_path, format="wav")
            print(f"Converted to WAV: {wav_path}")
            output_path = wav_path

        return output_path

    def play_audio(self, audio_path):
        """
        Play the audio file in the notebook
        """
        display(Audio(audio_path))
        return audio_path

# Usage example
def run_example():
    tts = TTSWrapper()

    # Example with English
    text_en = "Hello, this is a test of the text to speech system."
    audio_path_en = tts.synthesize(text_en, lang='en')
    tts.play_audio(audio_path_en)

    # Example with Kinyarwanda
    text_rw = "Muraho neza! Nishimiye kubabona."
    audio_path_rw = tts.synthesize(text_rw, lang='rw')
    tts.play_audio(audio_path_rw)

    return "TTS processing complete!"

