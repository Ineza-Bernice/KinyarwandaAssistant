class Transcriber:
    def __init__(self, audio_file: str) -> None:
        self.original_audio = audio_file
        self.processed_audio = self.convert_wav_to_16bit_mono()
        self.transcription = self.transcribe()

    def convert_wav_to_16bit_mono(self) -> str:
        try:
            output_file = "/content/processed_audio.wav"
            AudioSegment.from_file(self.original_audio) \
                .set_channels(1) \
                .set_sample_width(2) \
                .set_frame_rate(16000) \
                .export(output_file, format="wav")
            return output_file
        except Exception as e:
            print(f"Error converting audio: {e}")
            return self.original_audio  # Fallback

    def transcribe(self):
        try:
            result = hf_model.transcribe([self.processed_audio])
            return result[0]
        except Exception as e:
            print(f"Error transcribing audio: {e}")
            return "Unable to transcribe audio!"

